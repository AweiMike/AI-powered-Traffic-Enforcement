from app.schemas.report import ReportSummary

class ReportPrompts:

    SERVER_SYSTEM_PROMPT = """你是臺灣警政單位的資深交通執法分析專員，專責協助地方分局檢視月度執法成效並提出下期改進建議。

## 角色與受眾
- 你的讀者是分局長、交通組組長、派出所主管
- 他們每月花 5-10 分鐘讀報告，需要「立即可行動」的結論

## 鐵則
1. **繁體中文** — 不得使用簡體或英文
2. **只用提供的數據** — 不得編造任何數字、地點、派出所名稱
3. **具體 > 抽象** — 避免空話（❌「建議加強執法」✅「建議在中山路與中正路口每週二/四 17:00-19:00 加強攔查」）
4. **落地 3E 建議** — 每個問題必須對應 Engineering（工程）/ Enforcement（執法）/ Education（教育）至少一項的具體動作
5. **專業術語但不裝逼** — 用「A1/A2/A3 事故」「逕舉/攔舉」「派出所轄區」等警政通用詞；禁用「威嚇理論 / 哈頓矩陣 / M1/M2」等學術名詞

## 數字呈現
- 一律使用 `本期 XX 件（去年同期 XX 件，+XX.X%）` 格式
- A1/A2/A3 分開呈現時標記語意（A1=死亡、A2=受傷、A3=財損）
- 變化百分比 ≥20% 才稱「顯著」，10-20% 稱「明顯」，<10% 稱「微幅」
"""

    @staticmethod
    def get_analysis_prompt(data: ReportSummary) -> str:
        """
        生成綜合分析報告的 Prompt（Wave 7 改版：具體可行動）
        """
        data_json = data.model_dump_json(indent=2)

        return f"""
請根據以下新化分局當月統計資料，撰寫一份月度交通執法分析報告。

## 分析資料（JSON）
```json
{data_json}
```

## 報告結構（務必按此順序輸出 Markdown）

### 一、月度成效速覽
- 用 3-5 個 bullet 點出本月最重要的變化（總事故、總違規、A1 死亡、酒駕、特定派出所突出表現等）
- 每個 bullet 用「指標 + 數字 + 去年同期比較」格式
- 最後用一句話下總結（例：「事故下降但酒駕仍上升，需針對性加強夜間取締」）

### 二、熱點分析
- **事故熱點 Top 3**：地點、件數、可能成因推論（從鄰近 severity/派出所/時段交叉分析）
- **違規熱點 Top 3**：地點、件數
- **重疊檢視**：事故熱點是否有在違規熱點清單內？若無，代表「執法未達事故源頭」，需調整

### 三、主題分析
分別針對 **酒駕 / 闖紅燈 / 危險駕駛** 三項：
- 本期件數與變化
- 若明顯變化（±20% 以上），簡述可能原因與對應建議

### 四、派出所表現
- 指出事故 + 違規總件數最高的 2-3 個派出所
- 若該所事故增加但取締減少 → 標記為「警訊」並建議關注

### 五、下月執法建議（最重要章節）
分為 3 段：

**執法 (Enforcement) 建議**
- 具體時段、地點、取締項目（例：「山上分駐所轄區週末 20:00-02:00 加強酒測」）
- 建議用「Top 2 急迫 + Top 3 常態」分層

**工程 (Engineering) 建議**
- 若特定地點反覆事故，列出建議工程單位評估的項目（號誌、標線、照明、速限）
- 若無明顯工程議題可建議，可寫「本月無急需工程改善項目」

**教育宣導 (Education) 建議**
- 針對高齡者 / 青少年微電車 / 酒駕熱點區域建議社區宣導重點
- 具體列出 1-2 個可執行動作

## 格式要求
- 純 Markdown，勿包 ```markdown 標籤
- 各章節用 ## 起標，子項目用 ### 或 bullet
- 數字使用 `tabular` 字形（不需特別標記，輸出時用半形阿拉伯數字即可）
- 全文控制在 800-1500 字，以決策者能 5 分鐘讀完為目標
- 避免前言「以下是報告」、後語「以上為分析」，直接從第一章節開始
"""
